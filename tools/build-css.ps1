<#
  Regenerates tailwind.css from the Tailwind classes used in index.html.

  Run it again whenever you add or change Tailwind classes:
      powershell -ExecutionPolicy Bypass -File tools\build-css.ps1

  How it works: index.html is rendered in headless Edge/Chrome with the official
  Tailwind Play CDN, and the CSS that Tailwind generates is saved to tailwind.css.
  No Node.js required. Needs internet only while building, never at runtime.
#>
$ErrorActionPreference = 'Stop'

$TailwindVersion = '3.4.17'
# Classes that are only added by JavaScript at runtime (not in the DOM on load)
$Safelist = 'opacity-0 opacity-100 pointer-events-none'

$root = Split-Path -Parent $PSScriptRoot
$browser = @(
  "${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
  "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe",
  "$env:ProgramFiles\Google\Chrome\Application\chrome.exe"
) | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $browser) { throw 'Microsoft Edge or Google Chrome is required.' }

# Build page = index.html with the local stylesheet swapped for the Tailwind CDN
$html = [IO.File]::ReadAllText((Join-Path $root 'index.html'))
$link = '<link rel="stylesheet" href="tailwind.css">'
if (-not $html.Contains($link)) { throw "index.html must contain: $link" }
$html = $html.Replace($link, "<script src=`"https://cdn.tailwindcss.com/$TailwindVersion`"></script>")
$html = $html.Replace('</body>', "<div hidden class=`"$Safelist`"></div></body>")

$tmp = Join-Path $env:TEMP ('tw-build-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $tmp | Out-Null
$page = Join-Path $tmp 'build.html'
[IO.File]::WriteAllText($page, $html, (New-Object System.Text.UTF8Encoding $false))

$url = 'file:///' + ($page -replace '\\', '/')
# The browser writes harmless log noise to stderr; don't treat that as a failure.
$ErrorActionPreference = 'Continue'
$dom = & $browser --headless=new --disable-gpu --no-first-run --no-default-browser-check `
  "--user-data-dir=$tmp\profile" --virtual-time-budget=10000 --dump-dom $url 2>$null | Out-String
$ErrorActionPreference = 'Stop'

$match = [regex]::Match($dom, '(?s)<style[^>]*>((?:(?!</style>).)*?tailwindcss v(?:(?!</style>).)*)</style>')
if (-not $match.Success) { throw 'Could not find the generated Tailwind CSS. Is the internet connection working?' }

$header = "/* Generated by tools/build-css.ps1 from index.html (Tailwind CSS v$TailwindVersion). Do not edit by hand. */`n"
$css = $header + $match.Groups[1].Value.Trim() + "`n"
[IO.File]::WriteAllText((Join-Path $root 'tailwind.css'), $css, (New-Object System.Text.UTF8Encoding $false))

Start-Sleep -Milliseconds 500
Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
Write-Output ("tailwind.css written ({0:N0} bytes)" -f $css.Length)
